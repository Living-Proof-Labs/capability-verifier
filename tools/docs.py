"""Stage canonical Markdown and actual Task/scenario/test references."""

import hashlib
import json
import os
import re
import shutil
import subprocess
import tomllib
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "artifacts/docs"


def source_identity():
    paths = [*ROOT.glob("*.toml"), *ROOT.glob("*.yml"), ROOT / "uv.lock", ROOT / "Dockerfile"]
    for directory in ("src", "tests", "tools", "fixtures", "docs"):
        paths.extend(
            p
            for p in (ROOT / directory).rglob("*")
            if p.is_file() and "__pycache__" not in p.parts and p.suffix in (".py", ".md", ".json")
        )
    paths.append(ROOT / ".github/PAGES.md")
    paths.extend(ROOT.glob("*.md"))
    paths.extend(ROOT.glob("*.lock.json"))
    lock = json.loads((ROOT / "specs.lock.json").read_text())
    paths.extend(ROOT / ".specs" / name for name in lock["files"])
    return {
        str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(paths)
    }


def command(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def build():
    context = json.loads((ROOT / "artifacts/test-context.json").read_text())
    if context["sources"] != source_identity():
        raise ValueError("Verification inputs changed; run task verify before task docs")
    commit = os.environ.get("SOURCE_COMMIT") or command("git", "rev-parse", "HEAD")
    if context["commit"] != commit:
        raise ValueError("Verification revision changed; run task verify")
    report = ROOT / "artifacts/results.xml"
    if hashlib.sha256(report.read_bytes()).hexdigest() != context["junit_sha256"]:
        raise ValueError("JUnit differs from the completed verification run")
    cases = ET.parse(report).findall(".//testcase")
    if not cases or len(cases) != context["collected"]:
        raise ValueError("Missing or incomplete verification results")
    identities = [(c.get("classname"), c.get("name")) for c in cases]
    if len(identities) != len(set(identities)):
        raise ValueError("Duplicate verification results")
    if OUT.exists():
        shutil.rmtree(OUT)
    stage = OUT / "source"
    stage.mkdir(parents=True)
    mapping = {
        "README.md": "index.md",
        ".github/PAGES.md": "pages.md",
        "docs/documentation.md": "docs/documentation.md",
        "docs/matrix-validation.md": "docs/matrix-validation.md",
        "docs/guides.md": "docs/guides.md",
        "docs/contributing.md": "docs/contributing.md",
        "docs/license.md": "docs/license.md",
    }
    commit = context["commit"]
    rendered_paths = {**mapping, "tasks.md": "tasks.md", "provenance.md": "provenance.md"}
    for src, dest in mapping.items():

        def link(match):
            target = match.group(2)
            if "://" in target or target.startswith("#"):
                return match.group(0)
            path, _, fragment = target.partition("#")
            resolved = (ROOT / src).parent.joinpath(path).resolve().relative_to(ROOT).as_posix()
            if resolved in rendered_paths:
                target = os.path.relpath(stage / rendered_paths[resolved], (stage / dest).parent)
                if fragment:
                    target += "#" + fragment
            else:
                target = f"https://github.com/Living-Proof-Labs/capability-verifier/blob/{commit}/{resolved}"
                if fragment:
                    target += "#" + fragment
            return f"[{match.group(1)}]({target})"

        text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", link, (ROOT / src).read_text())
        target = stage / dest
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    tasks = [
        "# Task reference\n\nGenerated by Task 3.54.0 from this checkout.\n\n"
        "`Taskfile.yml` is the host wrapper using Docker Compose. "
        "Use `Taskfile.runtime.yml` inside the prepared container; it does not recurse through Docker. "
        "`Taskfile.reporter.yml` runs inside the pinned installed reporter environment."
    ]
    for taskfile in ("Taskfile.yml", "Taskfile.runtime.yml", "Taskfile.reporter.yml"):
        tasks.append(f"\n## {taskfile}\n")
        data = json.loads(command("task", "-t", taskfile, "--list-all", "--json"))
        for task in data["tasks"]:
            name = task["name"]
            tasks.append(
                f"\n### {name}\n\n```text\n"
                + command("task", "-t", taskfile, name, "--summary")
                + "\n```\n"
            )
    (stage / "tasks.md").write_text("\n".join(tasks))
    feature = (ROOT / ".specs/specs/v1/reference.feature").read_text()
    statuses = []
    for case in cases:
        status = (
            "failed"
            if case.find("failure") is not None or case.find("error") is not None
            else "skipped"
            if case.find("skipped") is not None
            else "passed"
        )
        statuses.append({"id": case.get("classname") + "::" + case.get("name"), "status": status})
    lines = [
        "# Scenarios and results",
        "",
        "Released robot-capability-specs v1.1.0, unmodified CC BY 4.0 scenario source.",
        "These are recorded fixture expectations, not robot safety certification.",
        "",
        "```gherkin",
        feature,
        "```",
        "",
        "## Executed inventory",
        "",
        "Every case below comes from the same verification JUnit report. The five",
        "`tests.test_reference` cases execute the feature above; the remaining",
        "cases cover the matrix, bundles and regression. Installed reporter archive",
        "consumption has separate native CI results. No line coverage is measured.",
        "",
        "| Test identity | Status |",
        "| --- | --- |",
    ]
    lines += [f"| `{s['id']}` | {s['status']} |" for s in statuses]
    (stage / "scenarios.md").write_text("\n".join(lines) + "\n")
    build_info = {
        **context,
        "junit_sha256": hashlib.sha256(report.read_bytes()).hexdigest(),
        "generator": "zensical 0.0.73",
    }
    (stage / "build.json").write_text(json.dumps(build_info, indent=2) + "\n")
    (stage / "feature-results.json").write_text(json.dumps(statuses, indent=2) + "\n")
    shutil.copyfile(report, OUT / "results.xml")
    package = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    (stage / "provenance.md").write_text(
        '<span id="version-context"></span>\n\n# Version and source\n\n'
        f"**Docs: development · {commit[:7]}** — "
        f"[exact source tree](https://github.com/Living-Proof-Labs/capability-verifier/tree/{commit}).\n\n"
        f"Full documentation source revision: `{commit}`.\n\n"
        f"Checkout identity: `{context['version']}`. Verification run: {context['run']}.\n\n"
        f"Python project metadata: `{package['version']}` (development placeholder). "
        "This is not a package release label. "
        "[Published verifier releases](https://github.com/Living-Proof-Labs/capability-verifier/releases) "
        "identify distributed versions separately from this moving development manual.\n\n"
        "Historical manuals are not maintained; consult the exact source release tag "
        "for installed versions. Fixture, catalog and executor versions remain the explicit "
        "released pins described in Start here and recorded in the manifests.\n\n"
        "[Build identity and source hashes](build.json) · [Individual outcomes](feature-results.json)\n"
    )
    for page in stage.rglob("*.md"):

        def relative(target):
            return os.path.relpath(stage / target, page.parent)

        footer = (
            "\n\n---\n\n"
            "[Documentation home](https://docs.livingprooflabs.com/) · "
            f"[Docs: development · {commit[:7]}]({relative('provenance.md')}) · "
            f"[Source](https://github.com/Living-Proof-Labs/capability-verifier/tree/{commit}) · "
            "[Help / report an issue](https://github.com/Living-Proof-Labs/capability-verifier/issues) · "
            f"[License]({relative('docs/license.md')})\n"
        )
        page.write_text(page.read_text() + footer)
    subprocess.run(["zensical", "build", "--clean"], cwd=ROOT, check=True)


if __name__ == "__main__":
    build()
