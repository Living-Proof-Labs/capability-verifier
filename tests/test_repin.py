"""capability_verifier.repin: release refs in a robot repository's verification.lock.json.
Moved here from each robot repository's tools/repin.py (fixture: the G1 lock)."""

import json
import shutil
from pathlib import Path

import pytest

from capability_verifier import repin

FIXTURE = Path(__file__).parent / "fixtures" / "repin"
LOCK = json.loads((FIXTURE / "verification.lock.json").read_text())
PYPROJECT = (FIXTURE / "pyproject.toml").read_text()
DIGEST = "sha256:" + "d" * 64


def pending_lock():
    """The lock as it was before any release was pinned."""
    lock = json.loads(json.dumps(LOCK))
    for name in ("runner", "verifier", "reporter"):
        lock["releases"][name].update(tag="PENDING_RELEASE", commit="PENDING_RELEASE")
        lock["releases"][name].pop("digest", None)
    return lock


def test_repin_fills_lock_and_runner_source_from_resolved_tags():
    commits = {"runner": "1" * 40, "verifier": "2" * 40, "reporter": "3" * 40}
    by_repo = {LOCK["releases"][k]["repository"]: v for k, v in commits.items()}
    pins = {"runner": "v1.4.0", "verifier": "v1.8.0", "reporter": "v1.7.0"}
    pyproject_pending = PYPROJECT.replace('tag = "v1.4.0"', 'rev = "' + "0" * 40 + '"')
    lock, pyproject, changes = repin.repin(
        pending_lock(),
        pyproject_pending,
        pins,
        lambda repo, tag: by_repo[repo],
        lambda image, tag: DIGEST,
    )
    for name, tag in pins.items():
        assert lock["releases"][name]["tag"] == tag
        assert lock["releases"][name]["commit"] == commits[name]
        assert "expected" not in lock["releases"][name]
    assert lock["releases"]["specs"] == LOCK["releases"]["specs"]
    assert lock["releases"]["reporter"]["image"] == LOCK["releases"]["reporter"]["image"]
    assert lock["releases"]["reporter"]["digest"] == DIGEST
    assert "digest" not in lock["releases"]["runner"]
    assert (
        'livingproof-sim-mujoco = { git = "https://github.com/Living-Proof-Labs/'
        'livingproof-sim-mujoco.git", tag = "v1.4.0" }'
    ) in pyproject
    assert "rev = " not in repin.runner_source(pyproject)
    assert repin.check(lock, pyproject) == []
    assert changes[-1] == "uv.lock: regenerated by uv lock"
    assert f"releases.reporter.digest: PENDING_RELEASE -> {DIGEST}" in changes
    assert {k: v for k, v in lock.items() if k != "releases"} == {
        k: v for k, v in LOCK.items() if k != "releases"
    }


def test_repin_never_invents_a_tag():
    def missing(repo, tag):
        raise SystemExit(f"{repo} has no tag {tag}")

    with pytest.raises(SystemExit, match="has no tag v9.9.9"):
        repin.repin(LOCK, PYPROJECT, {"runner": "v9.9.9"}, missing)
    with pytest.raises(SystemExit, match="expected vX.Y.Z"):
        repin.repin(LOCK, PYPROJECT, {"runner": "main"}, missing)


def test_check_rejects_path_pins_and_a_runner_off_its_locked_tag():
    lock = json.loads(json.dumps(LOCK))
    for ref in lock["releases"].values():
        ref.update(tag="v1.0.0", commit="a" * 40)
    lock["releases"]["reporter"]["digest"] = DIGEST
    assert not any("digest" in p for p in repin.check(lock, PYPROJECT))
    del lock["releases"]["reporter"]["digest"]
    assert any(
        "reporter has an image but no sha256 digest" in p for p in repin.check(lock, PYPROJECT)
    )
    lock["releases"]["reporter"]["digest"] = DIGEST
    pinned = PYPROJECT.replace(
        "livingproof-sim-mujoco = { git", 'livingproof-sim-mujoco = { path = "/tmp/runner", git'
    )
    assert any("path-pinned" in p for p in repin.check(lock, pinned))
    assert any("not tag v1.0.0" in p for p in repin.check(lock, PYPROJECT))


def test_reporter_digest_is_never_invented():
    def unpublished(image, tag):
        raise SystemExit(f"{image}:{tag} is not published (404); release it first")

    with pytest.raises(SystemExit, match="is not published"):
        repin.repin(
            pending_lock(),
            PYPROJECT,
            {"reporter": "v1.7.1"},
            lambda repo, tag: "3" * 40,
            unpublished,
        )


def test_repin_writes_the_lock_in_its_committed_layout():
    text = (FIXTURE / "verification.lock.json").read_text()
    assert repin.dump(json.loads(text)) == text


def locked_commits(repository, tag):
    return next(
        r["commit"]
        for r in LOCK["releases"].values()
        if r["repository"] == repository and r["tag"] == tag
    )


def locked_digests(image, tag):
    return next(
        r["digest"]
        for r in LOCK["releases"].values()
        if r.get("image") == image and r["tag"] == f"v{tag}"
    )


def with_verifier_image(digest=DIGEST, image=repin.VERIFIER_IMAGE):
    lock = json.loads(json.dumps(LOCK))
    lock["releases"]["verifier"].update(image=image, digest=digest)
    return lock


def test_verifier_hallway_image_needs_a_digest_and_the_hallway_name():
    assert repin.check(with_verifier_image(), PYPROJECT) == []
    no_digest = with_verifier_image()
    del no_digest["releases"]["verifier"]["digest"]
    assert "releases.verifier has an image but no sha256 digest" in repin.check(
        no_digest, PYPROJECT
    )
    other = with_verifier_image(image="ghcr.io/someone/else")
    assert any(
        "releases.verifier.image is 'ghcr.io/someone/else'" in p
        for p in repin.check(other, PYPROJECT)
    )


def test_check_confirms_each_image_tag_has_its_locked_digest():
    lock = with_verifier_image()
    published = {repin.VERIFIER_IMAGE: DIGEST, LOCK["releases"]["reporter"]["image"]: None}

    def registry(image, tag):
        return published[image] or locked_digests(image, tag)

    assert repin.check(lock, PYPROJECT, locked_commits, registry) == []
    published[repin.VERIFIER_IMAGE] = "sha256:" + "e" * 64
    tag = LOCK["releases"]["verifier"]["tag"].removeprefix("v")
    assert repin.check(lock, PYPROJECT, locked_commits, registry) == [
        f"releases.verifier: {repin.VERIFIER_IMAGE}:{tag} is sha256:{'e' * 64}, "
        f"not the locked {DIGEST}"
    ]
    assert repin.check(lock, PYPROJECT) == []  # offline: format only


def test_check_reports_an_unpublished_image():
    def unpublished(image, tag):
        raise SystemExit(f"{image}:{tag} is not published (404); release it first")

    problems = repin.check(with_verifier_image(), PYPROJECT, locked_commits, unpublished)
    assert len(problems) == 2 and all("not published" in p for p in problems)


def test_check_confirms_each_tag_resolves_to_its_locked_commit():
    assert repin.check(LOCK, PYPROJECT, locked_commits) == []
    moved = json.loads(json.dumps(LOCK))
    moved["releases"]["verifier"]["commit"] = "e" * 40
    problems = repin.check(moved, PYPROJECT, locked_commits)
    assert problems == [
        f"releases.verifier: {LOCK['releases']['verifier']['repository']} tag "
        f"{LOCK['releases']['verifier']['tag']} is {LOCK['releases']['verifier']['commit']}, "
        f"not the locked {'e' * 40}"
    ]
    assert repin.check(moved, PYPROJECT) == []  # offline: format only, as before


def test_check_reports_a_tag_that_no_longer_resolves():
    def gone(repository, tag):
        raise SystemExit(f"{repository} has no tag {tag}; release it first")

    problems = repin.check(LOCK, PYPROJECT, gone)
    assert len(problems) == len(LOCK["releases"])
    assert all("cannot resolve" in p and "has no tag" in p for p in problems)


def test_cli_check_resolves_tags_unless_offline(tmp_path, capsys, monkeypatch):
    shutil.copy(FIXTURE / "verification.lock.json", tmp_path)
    shutil.copy(FIXTURE / "pyproject.toml", tmp_path)
    monkeypatch.setattr(repin, "resolve", lambda repository, tag: "0" * 40)
    monkeypatch.setattr(repin, "image_digest", locked_digests)
    assert repin.main(["--root", str(tmp_path), "--check"]) == 1
    assert "not the locked" in capsys.readouterr().out
    assert repin.main(["--root", str(tmp_path), "--check", "--offline"]) == 0


def test_cli_checks_the_robot_repository_named_by_root(tmp_path, capsys, monkeypatch):
    monkeypatch.setattr(repin, "resolve", locked_commits)
    monkeypatch.setattr(repin, "image_digest", locked_digests)
    shutil.copy(FIXTURE / "verification.lock.json", tmp_path)
    shutil.copy(FIXTURE / "pyproject.toml", tmp_path)
    assert repin.main(["--root", str(tmp_path), "--check"]) == 0
    assert "every ref is a released tag" in capsys.readouterr().out
    lock = pending_lock()
    (tmp_path / "verification.lock.json").write_text(repin.dump(lock))
    assert repin.main(["--root", str(tmp_path), "--check"]) == 1
    assert "NOT RELEASED: releases.runner is PENDING_RELEASE" in capsys.readouterr().out
